#!/usr/bin/env bash
# Writes the per-audience entry points of packages/offers_api, so each app
# only sees the endpoints meant for it:
#
#   package:offers_api/auth.dart      login, tokens, profile, app config (all apps)
#   package:offers_api/business.dart  store app
#   package:offers_api/customer.dart  customer app
#   package:offers_api/admin.dart     admin dashboard
#
# Models are shared by all entry points. Called by tool/generate_api.sh.
set -euo pipefail

PKG="$(cd "$(dirname "$0")/../packages/offers_api" && pwd)"
GEN="$PKG/lib/src/generated"
cd "$GEN/clients"

header() {
  cat <<HEADER
// GENERATED by tool/write_api_entrypoints.sh - DO NOT EDIT.
// $1
library;

HEADER
}

{
  echo "// GENERATED by tool/write_api_entrypoints.sh - DO NOT EDIT."
  echo "// All request and response models, shared by every entry point."
  for f in $(ls "$GEN/models" | grep -v '\.g\.dart$' | sort); do
    echo "export 'generated/models/$f';"
  done
} > "$PKG/lib/src/models.dart"

write() { # file, description, client files...
  local file=$1 description=$2
  shift 2
  {
    header "$description"
    {
      echo "export 'src/models.dart';"
      for client in "$@"; do echo "export 'src/generated/clients/$client';"; done
    } | sort
  } > "$PKG/lib/$file"
}

write auth.dart "Shared by all apps: login, tokens, profile, app config." \
  auth_client.dart app_config_client.dart health_client.dart
write business.dart "Store app: the store, products, offers, claims at the counter." \
  $(ls business_*_client.dart | sort)
write customer.dart "Customer app: browsing, store pages, claims, follows." \
  offers_client.dart stores_client.dart claims_client.dart categories_client.dart
write admin.dart "Admin dashboard." \
  $(ls admin_*_client.dart | sort) categories_client.dart

# Every generated client must belong to an entry point.
for client in *_client.dart; do
  [[ "$client" == *.g.dart ]] && continue
  grep -q "clients/$client'" "$PKG"/lib/*.dart || {
    echo "Client $client is not exported by any entry point; update $0" >&2
    exit 1
  }
done
echo "Wrote entry points: auth, business, customer, admin"
